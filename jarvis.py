    # 🧠 Central Intelligence Router
    def handle_command(self, cmd):
        c = cmd.strip()
        c_low = c.lower()
        if not c:
            return

        if c_low in ["exit", "quit", "shutdown", "bye", "band karo"]:
            self.speak(f"Shutting down core systems. Goodbye {self.user_name}!")
            return "EXIT"

        # Voice control
        elif "voice off" in c_low or "mute" in c_low:
            self.voice_enabled = False
            print("[Voice Disabled]")
        elif "voice on" in c_low or "unmute" in c_low:
            self.voice_enabled = True
            self.speak("Voice synthesizer active.")

        # Code Generation
        elif any(w in c_low for w in ["generate", "code", "banao", "create", "website", "game", "calculator", "prime"]):
            self.tool_generate_code(c)

        # App Launch
        elif any(w in c_low for w in ["open", "launch", "kholo", "chalao"]) and not c_low.startswith("run code"):
            self.tool_open_app(c)

        # Search / Play Media
        elif any(w in c_low for w in ["search", "find", "google", "play", "gana", "song"]):
            self.tool_search_web(c)

        # Math / Currency
        elif any(w in c_low for w in ["calculate", "calc", "math", "+", "*", "/", "usd", "inr"]) and any(char.isdigit() for char in c):
            self.tool_math(c)

        # Execute Script
        elif c_low.startswith("run"):
            parts = c.split(" ", 2)
            fname = parts[-1] if len(parts) > 1 and parts[-1].endswith(".py") else "generated_calculator.py"
            self.tool_run_code(fname)

        # Notes
        elif "save note" in c_low or "add note" in c_low:
            self.tool_notes(c, mode="save")
        elif "show note" in c_low or "read note" in c_low or "notes" == c_low:
            self.tool_notes(c, mode="read")

        # Time / Date / Diagnostics
        elif "time" in c_low or "samay" in c_low:
            now = datetime.datetime.now().strftime("%I:%M %p")
            print(f"[Time] {now}")
            self.speak(f"The current time is {now}")
        elif "date" in c_low or "tarikh" in c_low:
            today = datetime.datetime.now().strftime("%A, %B %d, %Y")
            print(f"[Date] {today}")
            self.speak(f"Today is {today}")

        # Who are you / status
        elif "who are you" in c_low or "status" in c_low or "kaun ho" in c_low:
            self.speak("I am JARVIS, your personal autonomous AI agent system, engineered for Mohit.")

        else:
            self.speak(f"Executing protocol for {c}")
            self.tool_generate_code(c)

    def run(self):
        self.banner()
        while True:
            try:
                user_cmd = input(f"\n[⚡ {self.user_name}] >> ")
                status = self.handle_command(user_cmd)
                if status == "EXIT":
                    break
            except KeyboardInterrupt:
                self.speak(f"Process terminated. Goodbye {self.user_name}!")
                break
            except Exception as e:
                print(f"[System Error] {e}")

