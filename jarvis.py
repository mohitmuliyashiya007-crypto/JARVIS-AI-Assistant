    # 🛠️ TOOL 2: App & System Launcher
    def tool_open_app(self, query):
        q = query.lower()
        if "chrome" in q or "browser" in q:
            self.speak("Opening Google Chrome.")
            webbrowser.open("https://www.google.com")
        elif "youtube" in q:
            self.speak("Launching YouTube.")
            webbrowser.open("https://www.youtube.com")
        elif "notepad" in q:
            self.speak("Launching Notepad.")
            subprocess.Popen(["notepad.exe"])
        elif "calc" in q or "calculator" in q:
            self.speak("Launching Calculator.")
            subprocess.Popen(["calc.exe"])
        elif "cmd" in q or "terminal" in q:
            self.speak("Opening Command Prompt.")
            subprocess.Popen(["cmd.exe"])
        elif "code" in q or "vs code" in q or "vscode" in q:
            self.speak("Opening Visual Studio Code.")
            subprocess.Popen(["code"])
        else:
            self.speak("Target application not identified. Opening browser.")
            webbrowser.open("https://www.google.com")

    # 🛠️ TOOL 3: Real-Time Web Search & Media Player
    def tool_search_web(self, query):
        q = query.replace("search", "").replace("google", "").replace("find", "").replace("play", "").strip()
